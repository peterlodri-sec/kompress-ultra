# ── Hive orchestration ──────────────────────────────────────────────────
hive_list() {
  echo "=== Hive Researchers ==="
  declare -F | grep '^declare -f researcher_' | sed 's/declare -f researcher_//' | while read -r name; do
    echo -n "  ${name}  —  "
    eval "researcher_${name}" 2>/dev/null | head -1
  done | column -t -s '—'
  echo ""
  echo "Total: $(declare -F | grep -c '^declare -f researcher_') researchers"
}

hive_show() {
  local name="$1"
  if declare -F "researcher_${name}" &>/dev/null; then
    eval "researcher_${name}"
  else
    echo "unknown researcher: ${name}"
    echo "available:"
    declare -F | grep '^declare -f researcher_' | sed 's/declare -f researcher_//'
  fi
}

hive_random() {
  local researchers
  mapfile -t researchers < <(declare -F | grep '^declare -f researcher_' | sed 's/declare -f researcher_//')
  local r=$((RANDOM % ${#researchers[@]}))
  echo "=== Random Researcher: ${researchers[$r]} ==="
  eval "researcher_${researchers[$r]}"
}

case "${1:-list}" in
  list)     hive_list ;;
  show)     shift; hive_show "$@" ;;
  random)   hive_random ;;
  *)
    echo "hive-researchers — 25 experimental hive agents"
    echo "usage: source hive-researchers.sh {list|show <name>|random}"
    echo "  list    — show all 25 researchers"
    echo "  show X  — show researcher X's concept"
    echo "  random  — show a random researcher"
    ;;
esac
